export function getPost(slug: string): Post | undefined {
  return posts.find((post) => post.slug === slug);
}

export function getRelated(slug: string, count = 3): Post[] {
  const current = getPost(slug);
  if (!current) return posts.slice(0, count);
  const sameCategory = posts.filter((p) => p.slug !== slug && p.category === current.category);
  const others = posts.filter((p) => p.slug !== slug && p.category !== current.category);
  return [...sameCategory, ...others].slice(0, count);
}

export function wordCount(post: Post): number {
  return post.body.reduce((sum, block) => {
    if (block.type === "p" || block.type === "h2" || block.type === "h3" || block.type === "callout" || block.type === "quote") {
      return sum + (block as { text: string }).text.split(/\s+/).length;
    }
    if (block.type === "ul" || block.type === "ol") {
      return sum + block.items.join(" ").split(/\s+/).length;
    }
    if (block.type === "faq") {
      return sum + block.items.reduce((s, item) => s + (item.q + " " + item.a).split(/\s+/).length, 0);
    }
    return sum;
  }, 0);
}
